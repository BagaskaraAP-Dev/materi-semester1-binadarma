"""
Studi Kasus 3: Pembagian Permen Genap Sari
Konsep       : While Loop Step Increment (+2)
Deskripsi    : Sari membagikan permen dalam jumlah kelipatan genap
               mulai dari 2 hingga 10 butir permen.
"""

permen = 2  # Mulai dari 2 butir permen

while permen <= 10:
    print(permen, end=" ")
    permen += 2  # Bertambah kelipatan 2

print()
