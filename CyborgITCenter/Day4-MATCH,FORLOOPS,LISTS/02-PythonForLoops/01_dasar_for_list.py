# Iterasi List dengan For Loop

# Berbeda dengan loop di bahasa seperti C yang memakai indeks counter (i = 0; i < n; i++),
# for loop di Python bekerja langsung sebagai iterator pada koleksi data (sequence).

buah = ["apel", "pisang", "ceri"]

print("Daftar buah:")
for item in buah:
    print(item)
